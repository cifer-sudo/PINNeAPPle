"""Assemble candidates.md: hand-written candidate analysis + closest-paper tables pulled from lit/*.json (OpenAlex).

The closest-paper rows are the top OpenAlex relevance hits of the probe(s) named for each candidate. 'Abstract
excerpt' is the first sentence(s) of the OpenAlex abstract; when OpenAlex has none (Elsevier abstracts are often
withheld) the row says so, and the paper counts as NOT read.
"""
import json
import re

C = json.load(open("tools/candidates_text.json"))


def lit(tag):
    try:
        return json.load(open(f"lit/{tag}.json"))
    except FileNotFoundError:
        return None


def excerpt(a, n=230):
    if not a:
        return "abstract not available via OpenAlex (not read)"
    a = re.sub(r"\s+", " ", a.replace("|", "/"))
    return (a[:n] + "...") if len(a) > n else a


out = ["# Candidate PINN problems (Phase 2) and novelty / saturation check (Phase 3)", "",
       "Generated by `tools/build_candidates.py` from `tools/candidates_text.json` and the OpenAlex probes in `lit/`.",
       "Saturation counts = OpenAlex works whose title+abstract match the probe expression (probe and URL stored in",
       "`lit/<tag>.json`). Counts are a lower bound of the real literature (OpenAlex misses some IEEE/Elsevier items",
       "and does not index paywalled abstracts) and an upper bound of the *relevant* literature (keyword matches).",
       "", "Weeks are full-time-equivalent for one researcher with one GPU workstation.", ""]
out.append("| id | short title | saturation | probe count (2025 / 2026) |")
out.append("|---|---|---|---|")
for c in C:
    counts = []
    for t in c["probes"]:
        d = lit(t)
        if d:
            counts.append(f"{t}: {d['count']} ({d['by_year'].get('2025', 0)} / {d['by_year'].get('2026', 0)})")
    out.append(f"| {c['id']} | {c['title']} | **{c['saturation']}** | {'; '.join(counts)} |")
out.append("")
for c in C:
    out += [f"## {c['id']} — {c['title']}", ""]
    for k, lab in [("datasets", "Datasets"), ("physics", "Governing physics in the loss"), ("predicts", "Network predicts"),
                   ("supervision", "Supervision / held out"), ("why_not_dd", "Why a pure data-driven model is weaker"),
                   ("compute", "Compute / software / effort")]:
        out.append(f"- **{lab}.** {c[k]}")
    out += ["", "**Closest published work (OpenAlex top hits; read = abstract read):**", "",
            "| # | year | venue | DOI | title | abstract excerpt |", "|---|---|---|---|---|---|"]
    seen, n = set(), 0
    for t in c["probes"]:
        d = lit(t)
        if not d:
            continue
        for w in d["works"]:
            key = (w["title"] or "").lower()[:60]
            if key in seen or n >= 10:
                continue
            if c.get("min_year") and (w["year"] or 0) < c["min_year"]:
                continue
            seen.add(key)
            n += 1
            doi = (w["doi"] or "none").replace("https://doi.org/", "")
            out.append(f"| {n} | {w['year']} | {(w['venue'] or '')[:30]} | {doi} | {(w['title'] or '')[:95]} | {excerpt(w['abstract'])} |")
    out += ["", f"- **Already done.** {c['done']}", f"- **Not done.** {c['not_done']}", f"- **Gap (one sentence).** {c['gap']}",
            f"- **Saturation: {c['saturation']}.** {c['sat_evidence']}", f"- **Verdict.** {c['verdict']}", ""]
open("candidates.md", "w").write("\n".join(out))
print("candidates.md written,", len(C), "candidates")
