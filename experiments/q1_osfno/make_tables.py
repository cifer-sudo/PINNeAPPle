"""Deliverable tables, generated ONLY from result files (never typed): tables/*.csv and tables/*.tex.

  T01_main_macro_f1            every model x task: macro-F1 mean ± 95 % t-CI over 5 seeds, per held-out tercile, worst
  T02_balanced_accuracy        same for balanced accuracy
  T03_paired_comparisons       every pre-registered / reported paired comparison (seed diff, bands, bootstrap, McNemar, Holm)
  T04_phase3_locks             nested-selection choices per outer fold and inner scores
  T05_phase5b_decision         robust training: clean and robustness differences, pre-registered decision
  T06_phase7_compound          compound faults from singles
  T07_superposition            superposition error vs noise floor
  T08_robustness               test-time perturbations (speed error, dead sensor, gain x2)
  T09_calibration_cost         ECE, Brier, NLL, fit time, parameters
  T10_per_class_f1             per-class F1 (mean over seeds)
  T11_data                     data population and speed-tercile edges (audit)
usage: python make_tables.py
"""
